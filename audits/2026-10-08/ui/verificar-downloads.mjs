import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import { read, utils } from 'xlsx';
import { openPackage } from '../../../src/packages.js';
const folder = new URL('./', import.meta.url);
const downloadManifest = process.argv[2];
if (!downloadManifest) throw new Error('Passe o caminho de um JSON local com name/path dos cinco downloads sintéticos. Veja REPRODUCAO.md.');
const files = JSON.parse(await fs.readFile(downloadManifest, 'utf8'));
const get = async name => {
  const item = files.find(f => f.name === name);
  const bytes = await fs.readFile(item.path);
  return { bytes, item };
};
const excel = await get('Baixar Excel');
const workbook = read(excel.bytes, { type: 'array' });
const rows = utils.sheet_to_json(workbook.Sheets.Resultados);
const csv = await get('Baixar CSV');
const csvBook = read(csv.bytes, { type: 'array', raw: true });
const csvRows = utils.sheet_to_json(csvBook.Sheets[csvBook.SheetNames[0]]);
const complete = await get('Salvar pacote completo'), shared = await get('Salvar compartilhável');
const fullCase = await openPackage(new File([complete.bytes], 'completo.aircase'));
const sharedCase = await openPackage(new File([shared.bytes], 'compartilhavel.aircase'));
assert.equal(rows.length, 7);
assert.equal(csvRows.length, 7);
assert.equal(fullCase.run.id, sharedCase.run.id);
assert.equal(rows[0].execucao, fullCase.run.id);
assert.deepEqual(sharedCase.run.analysis, fullCase.run.analysis);
rows.forEach((row, i) => {
  assert.equal(row.media, fullCase.run.analysis.bins[i].mean);
  assert.equal(Number(csvRows[i].media), row.media);
});
assert.equal(fullCase.dataset.observations.length, 17676);
assert.equal(sharedCase.dataset.observations.length, 0);
assert.equal(sharedCase.dataset.hasInputs, false);
const pdf = await get('Baixar PDF');
assert.equal(pdf.bytes.subarray(0, 5).toString(), '%PDF-');
const proof = { execution: fullCase.run.id, rows: rows.length, completeObservations: fullCase.dataset.observations.length, sharedObservations: sharedCase.dataset.observations.length, mean: fullCase.run.analysis.summary.mean, used: fullCase.run.analysis.summary.n, coverage: fullCase.run.analysis.quality.coverage, matchingExcelCsvPackages: true, pdfHeaderValid: true };
await fs.writeFile(new URL('downloads-verificados.json', folder), JSON.stringify(proof, null, 2));
process.stdout.write(JSON.stringify(proof, null, 2));
